// 0.3.3 的回归：三份报告里的问题，一条一条钉住
//
// 全部用**假数据**跑，不依赖任何一台机器、任何一份真档案。
import { 排源会话, 该续批, 算该追加, 最晚有日记天 } from '../index.js'

let 挂 = 0
const 报 = (标, 过, 细) => {
  if (!过) 挂++
  console.log((过 ? 'PASS  ' : 'FAIL  ') + 标 + (细 ? '  :: ' + 细 : ''))
}

/* ① 「这些天都已经写过日记了」→ 进度该跟上到哪一天 */
{
  const 料 = [['2026-11-11'], ['2026-11-12'], ['2026-11-13'], ['2026-11-14']]
  const 有日记 = new Set(['2026-11-11', '2026-11-12', '2026-11-13', '2026-11-14'])
  报('进度跟上：全都有日记 → 走到最晚那天',
    最晚有日记天(料, (日) => 有日记.has(日)) === '2026-11-14',
    最晚有日记天(料, (日) => 有日记.has(日)))

  const 半 = new Set(['2026-11-11', '2026-11-12', '2026-11-14'])
  报('进度跟上：中间缺一天 → 只走到「确实写了」的最晚那天',
    最晚有日记天(料, (日) => 半.has(日)) === '2026-11-14',
    最晚有日记天(料, (日) => 半.has(日)))

  报('进度跟上：一天都没有 → 返回空（不乱推）',
    最晚有日记天(料, () => false) === '',
    最晚有日记天(料, () => false))
  报('进度跟上：空料不炸', 最晚有日记天([], () => true) === '', '')
}

/* ③ 选源：先看「进度之后还有几天」，再看总量 */
{
  // 用户实测的三张表：A 数据最多但只有已经整理完的那天
  const 候选 = [
    { id: 'A', 活: 0, 量: 609 },
    { id: 'B', 活: 2, 量: 527 },
    { id: 'C', 活: 2, 量: 483 },
    { id: 'D', 活: 1, 量: 447 },
    { id: 'E', 活: 1, 量: 304 },
  ]
  const 排好 = 排源会话(候选)
  报('选源：数据最多但没活的 A 不能排第一', 排好[0] !== 'A', 排好.join(' > '))
  报('选源：有活的按总量排（B 527 > C 483）', 排好[0] === 'B' && 排好[1] === 'C', 排好.join(' > '))
  报('选源：没活的排到最后', 排好[排好.length - 1] === 'A', 排好.join(' > '))

  const 都无活 = 排源会话([{ id: 'x', 活: 0, 量: 10 }, { id: 'y', 活: 0, 量: 99 }])
  报('选源：都没活时退回按总量', 都无活[0] === 'y', 都无活.join(' > '))

  报('选源：空候选不炸', 排源会话([]).length === 0, '')
  报('选源：候选里有脏数据也不炸', 排源会话([null, { id: 'z' }]).join() === 'z', '')
}

/* ⑦ 续批：只有「上一批没跑完」才沿用旧截止 */
{
  报('续批：手动点 → 用此刻（不沿用）', 该续批({ 手动: true, 完成: false, 截止: 1794438723338 }) === false, '')
  报('续批：上一批没跑完 → 沿用', 该续批({ 手动: false, 完成: false, 截止: 1794438723338 }) === true, '')
  报('续批：任务已经完成 → 用此刻（清掉旧截止）', 该续批({ 手动: false, 完成: true, 截止: 1794438723338 }) === false, '')
  报('续批：根本没有截止 → 用此刻', 该续批({ 手动: false, 完成: false, 截止: 0 }) === false, '')
}

/* ④ 原始对话：同一天第二次存，只追加新的那一段 */
{
  const 第一次 = '2026-11-15 原始对话\n10:00 她说：早\n11:00 我说：早呀'
  const 第二次 = 第一次 + '\n12:00 她说：吃饭了吗'
  const 第三次 = 第二次 + '\n13:00 她说：吃过了'

  const 空 = 算该追加('', 第一次)
  报('原始对话：文件不存在 → 整段写进去', 空.冲突 === false && 空.追加.includes('早'), '')

  const 二 = 算该追加(第一次, 第二次)
  报('原始对话：第二次存 → 追加新增那段', 二.冲突 === false && 二.追加.includes('吃饭了吗'), 二.追加.replace(/\n/g, ' | '))
  报('原始对话：追加的那段带「── 之后 ──」标记', 二.追加.includes('── 之后 ──'), '')

  const 重复 = 算该追加(第二次, 第二次)
  报('原始对话：同样内容再存一次 → 不追加', 重复.冲突 === false && 重复.追加 === '', '')

  // 真实的文件形状：第一次的全文 + 标记 + 第二次多出来的那段
  const 文件 = 第一次 + 二.追加
  const 再 = 算该追加(文件, 第三次)
  报('原始对话：带标记的旧文件也能接着追加', 再.冲突 === false && 再.追加.includes('吃过了'), 再.追加.replace(/\n/g, ' | '))

  const 撞 = 算该追加('完全不同的内容', 第三次)
  报('原始对话：内容对不上 → 报冲突、不写', 撞.冲突 === true && 撞.追加 === '', '')

  // 用户报的那个具体形状：文件已经 ≥200 字，新内容只是在后面多了一段
  const 长 = 'x'.repeat(300) + '\n尾巴'
  const 长2 = 'x'.repeat(300) + '\n尾巴\n新的消息'
  const 长判 = 算该追加(长, 长2)
  报('原始对话：旧文件 300 字时，新消息照样能追加（老代码在这里恒跳过）',
    长判.冲突 === false && 长判.追加.includes('新的消息'), '')
}

