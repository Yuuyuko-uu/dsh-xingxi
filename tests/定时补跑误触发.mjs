// 0.3.8 的回归：改定时设置不该把「昨天跑过」的记录一起清掉，
// 更不该在当天还没到点之前就补一批。
//
// 用户报的原话（大意）：把时间从 22:30 改成 23:00，22:00:50 就收到了
// 「到点了，今天的档案自己整理一下」的提醒，比设定早一小时。
//
// 原因：
//   ① 设置保存时 `清定时已发` 把整个会话的已发记录删了（连同昨天那条）
//   ② 补跑判断是「已发日 < 昨天就补」，空记录会穿过去 → 立刻派一批
//
// 跑法：node tests/定时补跑误触发.mjs
import assert from 'node:assert/strict'
import { 该清定时已发, 定时该补跑 } from '../index.js'

let 段 = 0
function 测(名, 做) {
  try { 做(); 段 += 1; console.log('PASS  ' + 名) }
  catch (e) { console.log('FAIL  ' + 名 + '  :: ' + ((e && e.message) || e)); process.exitCode = 1 }
}

const 今天 = '2026-11-17'
const 昨天 = '2026-11-16'
const 前天 = '2026-11-15'

/* ── 一、设置保存时该清哪一条 ───────────────────────────── */

测('存的是昨天：不许清（那是「昨天跑过」的证据）', () => {
  assert.equal(该清定时已发(昨天, 今天), false)
})

测('存的是今天：清掉，让今天可以重跑', () => {
  assert.equal(该清定时已发(今天, 今天), true)
})

测('从来没跑过（空）：没什么可清的', () => {
  assert.equal(该清定时已发('', 今天), false)
  assert.equal(该清定时已发(undefined, 今天), false)
})

/* ── 二、补跑该不该触发 ─────────────────────────────────── */

测('昨天跑过 → 不补（用户报的那一晚就属于这种）', () => {
  assert.equal(定时该补跑(昨天, 昨天), false)
})

测('今天已经跑过 → 不补', () => {
  assert.equal(定时该补跑(今天, 昨天), false)
})

测('没有任何记录 → 不补（空记录不等于漏跑）', () => {
  assert.equal(定时该补跑('', 昨天), false)
  assert.equal(定时该补跑(undefined, 昨天), false)
})

测('上一次是前天或更早 → 补一批', () => {
  assert.equal(定时该补跑(前天, 昨天), true)
  assert.equal(定时该补跑('2026-11-01', 昨天), true)
})

/* ── 三、把用户那一晚整条走一遍 ─────────────────────────── */

测('改设置 → 清记录 → 补跑判断：整条链路不该提前派', () => {
  // 21:59 那一刻：config 里 定时.已发[sid] = 昨天（11-16 写的日记）
  let 已发 = 昨天
  // 改时间，触发「变了」分支
  if (该清定时已发(已发, 今天)) 已发 = ''
  // 下一分钟调度器跑一轮，离 23:00 还早，走的是补跑分支
  assert.equal(定时该补跑(已发, 昨天), false, '不该补跑')
})

console.log('')
console.log('通过 ' + 段 + ' 项')
