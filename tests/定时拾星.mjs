// 定时拾星：到点不跑 / 当天被标记「已发」的回归测试
//
// 三个要求（用户报的那三条）：
//   ① 「已发」只在真派成时才写
//   ② 一轮只派一个，剩下的下一分钟接着派
//   ③ 空料不算完成，隔十分钟再试，23:59 收手
//
// 跑法： node tests/定时拾星.mjs

import { 定时下一步, 净会话名 } from '../index.js'

let 挂 = 0
const 报 = (标, 过, 细) => {
  if (!过) 挂++
  console.log((过 ? 'PASS  ' : 'FAIL  ') + 标 + (细 ? '  :: ' + 细 : ''))
}

// ③ 空料：10 分钟后再试，不算完成
const 空1 = 定时下一步({ 原因: '今天还没有新内容', 空料次数: 0, 现在分钟: 20 * 60 })
报('空料 → 等 10 分钟', 空1.等毫秒 === 10 * 60 * 1000, String(空1.等毫秒))
报('空料 → 不算完成', 空1.完 === false, String(空1.完))
报('空料 → 次数 +1', 空1.空料次数 === 1, String(空1.空料次数))

// ③ 23:59 收手
const 空2 = 定时下一步({ 原因: '今天还没有新内容', 空料次数: 3, 现在分钟: 23 * 60 + 59 })
报('23:59 之后空料 → 收手', 空2.完 === true, String(空2.完))

// ② 被节流挡住不算失败，下一分钟再来
const 节流 = 定时下一步({ 原因: '刚派过（同一个进程 30 秒内只派一个）', 空料次数: 0, 现在分钟: 20 * 60 })
报('刚派过 → 等 1 分钟', 节流.等毫秒 === 60 * 1000, String(节流.等毫秒))
报('刚派过 → 不算完成', 节流.完 === false, String(节流.完))

// 别的失败：5 分钟后再试
const 别的 = 定时下一步({ 原因: '建不了文件夹：EACCES', 空料次数: 0, 现在分钟: 20 * 60 })
报('别的失败 → 等 5 分钟', 别的.等毫秒 === 5 * 60 * 1000, String(别的.等毫秒))
报('别的失败 → 不算完成', 别的.完 === false, String(别的.完))

// 一轮只派一个 / 成功才写已发 —— 这两条是调度器里的流程，用假 ctx 跑一遍真的
const 源 = await import('node:fs').then((fs) => fs.readFileSync(new URL('../index.js', import.meta.url), 'utf8'))
报('调度器里「先写已发再派」那两行没了',
  !/日记已跑\.add\(键\)\s*\n\s*写定时已发/.test(源), '（查源码）')
报('派成功之后才写已发',
  /if \(成了\)[\s\S]{0,240}写定时已发\(会话id, 日\)/.test(源), '（查源码）')
报('一轮只派一个（本轮派过）', /本轮派过 = true/.test(源) && /if \(本轮派过\) continue/.test(源), '（查源码）')
报('有重入保护（派一批要几十秒）', /查定时跑着/.test(源), '（查源码）')

// 标题不许越叠越长（issue #4）
报('剥掉叠起来的「拾星 · 」前缀',
  净会话名('拾星 · 拾星 · 拾星 · 本机自动化任务挂载 · 2026-11-07') === '本机自动化任务挂载',
  净会话名('拾星 · 拾星 · 拾星 · 本机自动化任务挂载 · 2026-11-07'))
报('干净的源会话名原样返回', 净会话名('本机自动化任务挂载') === '本机自动化任务挂载', 净会话名('本机自动化任务挂载'))
报('再拼一次标题不会出现两个日期',
  '拾星 · ' + 净会话名('拾星 · 本机自动化任务挂载 · 2026-11-07') + ' · 2026-11-08' === '拾星 · 本机自动化任务挂载 · 2026-11-08',
  '拾星 · ' + 净会话名('拾星 · 本机自动化任务挂载 · 2026-11-07') + ' · 2026-11-08')

console.log('')
console.log(挂 === 0 ? '全过' : ('挂了 ' + 挂 + ' 条'))
process.exit(挂 === 0 ? 0 : 1)
